"""Hand-labeled gold set.

Labels follow the rubric in docs/JUDGE_RUBRIC.md. They were not copied from the heuristic.
Three items are deliberate disagreements (paraphrase, negation, an extra clause the overlap
check cannot see). The regressed side is a seeded prompt, `lumen-v2.4` / `aegis-policy-v8`,
used only to prove the gate fails closed.

`gold_*` describes the baseline output. `regressed_defect` describes what the seeded
candidate breaks relative to that baseline.
"""

from __future__ import annotations

from lens.models import GoldCase

REFUSAL = "Not found in the provided documents."


def _case(
    *,
    id: str,
    app: str,
    category: str,
    question: str,
    context: tuple[str, ...],
    output: str,
    faithful: bool,
    relevant: bool,
    safe: bool,
    refusal_correct: bool,
    note: str,
    output_regressed: str | None = None,
    top_score: float | None = 0.86,
    safety_critical: bool = False,
    route: str | None = None,
    route_regressed: str | None = None,
    label: str | None = None,
    label_regressed: str | None = None,
    latency: int = 640,
    latency_regressed: int | None = None,
    regressed_defect: str | None = None,
    known_heuristic_gap: str | None = None,
) -> GoldCase:
    return GoldCase(
        id=id,
        app=app,
        category=category,
        safety_critical=safety_critical,
        question=question,
        context=context,
        top_score=top_score,
        route_baseline=route,
        route_regressed=route if route_regressed is None else route_regressed,
        label_baseline=label,
        label_regressed=label if label_regressed is None else label_regressed,
        output_baseline=output,
        output_regressed=output if output_regressed is None else output_regressed,
        latency_ms_baseline=latency,
        latency_ms_regressed=latency if latency_regressed is None else latency_regressed,
        gold_faithful=faithful,
        gold_relevant=relevant,
        gold_safe=safe,
        gold_refusal_correct=refusal_correct,
        regressed_defect=regressed_defect,
        known_heuristic_gap=known_heuristic_gap,
        note=note,
    )


def _lumen(
    id: str,
    category: str,
    question: str,
    context: str,
    output: str,
    *,
    faithful: bool = True,
    relevant: bool = True,
    safe: bool = True,
    refusal_correct: bool = True,
    note: str = "",
    **kwargs: object,
) -> GoldCase:
    return _case(
        id=id,
        app="lumen",
        category=category,
        question=question,
        context=(context,),
        output=output,
        faithful=faithful,
        relevant=relevant,
        safe=safe,
        refusal_correct=refusal_correct,
        note=note,
        **kwargs,  # type: ignore[arg-type]
    )


