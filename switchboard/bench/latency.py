"""Measure router overhead. Catalog model latency is not included.

python bench/latency.py
python bench/latency.py --n 400 --warmup 30
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from switchboard.demo_data import EASY_CHAT, HARD_MATH, MEDIUM_CODE, SENSITIVE
from switchboard.pipeline import RouteRequest, route
from switchboard.runtime import Runtime
from switchboard.settings import Settings
from switchboard.store import percentile

PROMPTS = (
    ("default", EASY_CHAT, None),
    ("cost-saver", EASY_CHAT, None),
    ("quality-first", EASY_CHAT, None),
    ("default", MEDIUM_CODE, None),
    ("default", HARD_MATH, None),
    ("default", SENSITIVE, None),
    ("latency-first", HARD_MATH, None),
)


def run(n: int, warmup: int) -> dict[str, object]:
    runtime = Runtime(Settings(db_path=":memory:"))
    overhead: list[float] = []
    simulated: list[float] = []
    for index in range(warmup + n):
        policy_name, prompt, _fault = PROMPTS[index % len(PROMPTS)]
        decision = route(
            catalog=runtime.catalog,
            policy=runtime.policy(policy_name),
            provider=runtime.provider,
            store=runtime.store,
            request=RouteRequest(prompt=prompt),
        )
        if index < warmup:
            continue
        overhead.append(decision["timing"]["router_overhead_ms"])
        simulated.append(decision["timing"]["simulated_latency_ms"])
    return {
        "n": n,
        "warmup": warmup,
        "includes_sqlite_append": True,
        "sleep": False,
        "router_overhead_ms": {
            "p50": round(percentile(overhead, 50), 3),
            "p95": round(percentile(overhead, 95), 3),
            "p99": round(percentile(overhead, 99), 3),
            "max": round(max(overhead), 3),
        },
        "catalog_latency_ms": {
            "p50": round(percentile(simulated, 50), 2),
            "p95": round(percentile(simulated, 95), 2),
            "note": "Catalog estimate of the chosen model. Not wall clock.",
        },
        "mix": [item[0] for item in PROMPTS],
    }


def render(result: dict[str, object]) -> str:
    overhead = result["router_overhead_ms"]
    catalog = result["catalog_latency_ms"]
    assert isinstance(overhead, dict)
    assert isinstance(catalog, dict)
    return "\n".join(
        [
            "# Router overhead",
            "",
            "Generated by `make bench`.",
            "",
            f"n={result['n']} after {result['warmup']} warmup calls. "
            "Each call classifies, scores, invokes the in-process mock (no sleep), and appends a SQLite row.",
            "Catalog model latency is not slept and is not part of the overhead number.",
            "",
            "| Metric | Value | What it is |",
            "|---|---:|---|",
            f"| Router overhead p50 | {overhead['p50']} ms | Measured wall clock |",
            f"| Router overhead p95 | {overhead['p95']} ms | Measured wall clock |",
            f"| Router overhead p99 | {overhead['p99']} ms | Measured wall clock |",
            f"| Router overhead max | {overhead['max']} ms | Measured wall clock |",
            f"| Catalog latency p50 | {catalog['p50']} ms | Estimate, not measured |",
            f"| Catalog latency p95 | {catalog['p95']} ms | Estimate, not measured |",
            "",
            "The mix rotates easy chat, a code edit, hard math, a confidential note, and a latency-first rejection.",
            "",
        ]
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--n", type=int, default=400)
    parser.add_argument("--warmup", type=int, default=30)
    args = parser.parse_args()
    result = run(args.n, args.warmup)
    folder = Path(__file__).resolve().parents[1] / "reports"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "latency.json").write_text(json.dumps(result, indent=2) + "\n")
    (folder / "latency.md").write_text(render(result))
    overhead = result["router_overhead_ms"]
    assert isinstance(overhead, dict)
    print(f"router overhead p50 {overhead['p50']} ms  p95 {overhead['p95']} ms")


if __name__ == "__main__":
    main()
