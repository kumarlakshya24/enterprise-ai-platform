"""Write eval reports from a live corpus run."""

from __future__ import annotations

import json
from pathlib import Path

from forge.config import PROJECT_ROOT
from forge.corpus import load_cases, run_cases
from forge.policy.regression import CaseResult, GateReport, gate, load_baseline

REPORTS = PROJECT_ROOT / "reports"


def run_eval(work_root: Path | None = None) -> int:
    cases = load_cases()
    root = work_root or (PROJECT_ROOT / "var" / "eval")
    results = run_cases(cases, work_root=root)
    report = gate(results, load_baseline())
    _write_eval(results)
    _write_regression(results, report)
    failed = [item for item in results if not item.ok]
    print(
        f"cases={len(results)} failed={len(failed)} "
        f"protection_regressions={len(report.protection_regressions)} "
        f"utility_regressions={len(report.utility_regressions)}"
    )
    for item in failed:
        print(f"FAIL {item.id} {item.detail} outcome={item.outcome} rule={item.rule}")
    for item in report.protection_regressions:
        print(f"REGRESSION {item['case']} {item['outcome']} {item['rule']}")
    if failed or not report.ok:
        return 1
    return 0


def _write_eval(results: list[CaseResult]) -> None:
    passed = sum(1 for item in results if item.ok)
    by_class: dict[str, list[CaseResult]] = {}
    for item in results:
        by_class.setdefault(item.klass, []).append(item)
    lines = [
        "# Forge eval",
        "",
        "Generated by `make eval`. Do not edit by hand.",
        "",
        f"* Cases: **{len(results)}**",
        f"* Passed: **{passed}**",
        f"* Pass rate: **{passed / len(results):.1%}**",
        "",
        "| Class | Cases | Passed |",
        "|---|---:|---:|",
    ]
    for name, items in sorted(by_class.items()):
        lines.append(f"| {name} | {len(items)} | {sum(1 for item in items if item.ok)} |")
    missed = [item for item in results if not item.ok]
    if missed:
        lines += ["", "## Failures", "", "| Case | Expected | Outcome | Rule | Detail |", "|---|---|---|---|---|"]
        for item in missed:
            lines.append(f"| {item.id} | {item.expect} | {item.outcome} | {item.rule} | {item.detail} |")
    lines.append("")
    _write("eval.md", "\n".join(lines))
    _write(
        "eval.json",
        json.dumps(
            {
                "cases": len(results),
                "passed": passed,
                "pass_rate": passed / len(results),
                "results": [
                    {
                        "id": item.id,
                        "class": item.klass,
                        "expect": item.expect,
                        "outcome": item.outcome,
                        "rule": item.rule,
                        "ok": item.ok,
                        "spawned": item.spawned,
                    }
                    for item in results
                ],
            },
            indent=2,
        )
        + "\n",
    )


def _write_regression(results: list[CaseResult], report: GateReport) -> None:
    baseline = load_baseline()
    lines = [
        "# Forge regression gate",
        "",
        "Generated by `make eval`. Do not edit by hand.",
        "",
        f"* Baseline protected cases: **{len(baseline['protected'])}**",
        f"* Baseline utility cases: **{len(baseline['utility'])}**",
        f"* Protection regressions: **{len(report.protection_regressions)}**",
        f"* Utility regressions (warnings): **{len(report.utility_regressions)}**",
        f"* Result: **{'PASS' if report.ok else 'FAIL'}**",
        "",
        "A protection regression means a case the baseline kept non-allow is now allowed.",
        "That fails the gate. Utility regressions are warnings.",
        "",
    ]
    if report.protection_regressions:
        lines += ["## Protection regressions", "", "| Case | Outcome | Rule |", "|---|---|---|"]
        for item in report.protection_regressions:
            lines.append(f"| {item['case']} | {item['outcome']} | {item['rule']} |")
        lines.append("")
    if report.utility_regressions:
        lines += ["## Utility regressions", "", "| Case | Outcome | Rule |", "|---|---|---|"]
        for item in report.utility_regressions:
            lines.append(f"| {item['case']} | {item['outcome']} | {item['rule']} |")
        lines.append("")
    lines.append(f"Corpus cases executed: {len(results)}.")
    lines.append("")
    _write("regression.md", "\n".join(lines))


def _write(name: str, text: str) -> None:
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / name).write_text(text, encoding="utf-8")
