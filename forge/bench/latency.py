#!/usr/bin/env python3
"""Measure deny-path and allow-path latency. Writes reports/latency.md."""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from forge.audit import AuditLog  # noqa: E402
from forge.config import audit_key  # noqa: E402
from forge.service import Session  # noqa: E402
from forge.types import ToolRequest  # noqa: E402


def percentile(values: list[float], pct: float) -> float:
    ordered = sorted(values)
    index = min(len(ordered) - 1, max(0, round((pct / 100) * (len(ordered) - 1))))
    return ordered[index]


def sample(session: Session, request: ToolRequest, count: int) -> list[float]:
    timings: list[float] = []
    for _ in range(count):
        started = time.perf_counter()
        result = session.execute(request)
        timings.append((time.perf_counter() - started) * 1000)
        if request.tool == "python" and request.code and "import os" in request.code:
            if result.outcome != "deny":
                raise SystemExit(f"deny path returned {result.outcome}")
        elif result.outcome != "allow":
            raise SystemExit(f"allow path returned {result.outcome} {result.rule}")
    return timings


def main() -> int:
    root = ROOT / "var" / "bench"
    session = Session(root / "ws", AuditLog(root / "audit.jsonl", audit_key()))
    deny = sample(session, ToolRequest(tool="python", code='import os\nprint("RAN")'), 40)
    allow = sample(session, ToolRequest(tool="python", code="print(sum(range(1, 101)))"), 20)
    summary = {
        "deny_n": len(deny),
        "deny_p50_ms": round(percentile(deny, 50), 2),
        "deny_p95_ms": round(percentile(deny, 95), 2),
        "allow_n": len(allow),
        "allow_p50_ms": round(percentile(allow, 50), 2),
        "allow_p95_ms": round(percentile(allow, 95), 2),
    }
    lines = [
        "# Forge latency",
        "",
        "Generated by `make bench`. Do not edit by hand.",
        "",
        "The deny path is the guard only: `import os` does not spawn a process.",
        "The allow path includes one sandboxed interpreter.",
        "",
        "| Path | n | p50 | p95 |",
        "|---|---:|---:|---:|",
        f"| Deny before spawn | {summary['deny_n']} | {summary['deny_p50_ms']} ms | {summary['deny_p95_ms']} ms |",
        f"| Allow, subprocess | {summary['allow_n']} | {summary['allow_p50_ms']} ms | {summary['allow_p95_ms']} ms |",
        "",
    ]
    reports = ROOT / "reports"
    reports.mkdir(parents=True, exist_ok=True)
    (reports / "latency.md").write_text("\n".join(lines), encoding="utf-8")
    (reports / "latency.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(summary))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
