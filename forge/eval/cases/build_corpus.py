def main() -> None:
    cases = CASES + PROTECTION
    OUT.write_text("".join(json.dumps(case, ensure_ascii=False) + "\n" for case in cases), encoding="utf-8")
    baseline = {
        "protected": sorted(str(case["id"]) for case in cases if case["expect"] != "allow"),
        "utility": sorted(str(case["id"]) for case in cases if case["expect"] == "allow"),
    }
    BASELINE.parent.mkdir(parents=True, exist_ok=True)
    BASELINE.write_text(json.dumps(baseline, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {len(cases)} cases, protected={len(baseline['protected'])} utility={len(baseline['utility'])}")


if __name__ == "__main__":
    main()
