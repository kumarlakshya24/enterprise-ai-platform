#!/usr/bin/env python3
"""Run the demo and write reports/demo.md."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from forge.demo.runner import run_demo  # noqa: E402
from forge.reporting import REPORTS  # noqa: E402


def main() -> int:
    checks = run_demo()
    failed = 0
    lines = ["# Forge demo", "", "Generated by `make demo`. Do not edit by hand.", ""]
    for check in checks:
        mark = "PASS" if check.ok else "FAIL"
        if not check.ok:
            failed += 1
        print(f"{mark}  {check.id:<32} {check.detail}")
        lines.append(f"* **{mark}** `{check.id}` — {check.detail}")
    passed = len(checks) - failed
    print(f"\n{passed}/{len(checks)} passed")
    lines += ["", f"Result: **{passed}/{len(checks)} passed**.", ""]
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / "demo.md").write_text("\n".join(lines), encoding="utf-8")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
