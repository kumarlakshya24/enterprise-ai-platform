"""Red-team evaluation: precision, recall, false positives and false negatives over eval/cases/.

python eval/run_redteam.py            # writes reports/redteam.md and reports/redteam.json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from aegis.classifier.model import load_default_classifier  # noqa: E402
from aegis.dlp.engine import DLPEngine  # noqa: E402
from aegis.guard.injection import InjectionDetector  # noqa: E402
from aegis.policy.regression import CaseResult, Evaluator, load_cases, summarize  # noqa: E402
from aegis.policy.store import load_bundle_file  # noqa: E402

REPORT_MD = ROOT / "reports" / "redteam.md"
REPORT_JSON = ROOT / "reports" / "redteam.json"


def pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x * 100:.1f}%"


def main() -> int:
    cases = load_cases()
    policy = load_bundle_file().base
    dlp = DLPEngine.default("spacy")
    ev = Evaluator(dlp, load_default_classifier(), InjectionDetector())
    results = ev.evaluate(policy, cases)
    s = summarize(results)
    by_id = {c["id"]: c for c in cases}

    o = s["overall"]
    lines = [
        "# Red-team report",
        "",
        "Generated by `make redteam` (`python eval/run_redteam.py`) against the default policy. Do not edit by hand.",
        "",
        f"* Cases: **{o['cases']}** across {len(s['by_category'])} categories (`eval/cases/redteam.jsonl`)",
        f"* NER backend: `{dlp.ner_backend}`",
        "* A case is a **positive** if the gateway should protect something (PII, secret, sensitive context,",
        "  exfiltrating tool call, injected document) and a **negative** if it is legitimate work.",
        "* **TP**: protected as required. **FN**: something leaked or a route was weaker than required.",
        "  **FP**: legitimate work was redacted, over-routed, blocked, or flagged. **TN**: legitimate work untouched.",
        "",
        "This is a **development** red-team set: gaps found here are fixed and then locked in by the regression",
        "gate, so it is not a blind holdout. The blind holdout for the classifier is `reports/classifier.md`.",
        "",
        "## Overall",
        "",
        "| Cases | TP | FN | FP | TN | Recall | Precision |",
        "|-------|----|----|----|----|--------|-----------|",
        f"| {o['cases']} | {o['tp']} | {o['fn']} | {o['fp']} | {o['tn']} "
        f"| **{pct(o['recall'])}** | **{pct(o['precision'])}** |",
        "",
        "## By category",
        "",
        "| Category | Cases | TP | FN | FP | TN | Recall | Precision |",
        "|----------|-------|----|----|----|----|--------|-----------|",
    ]
    for cat, b in s["by_category"].items():
        lines.append(
            f"| {cat} | {b['cases']} | {b['tp']} | {b['fn']} | {b['fp']} | {b['tn']} "
            f"| {pct(b['recall'])} | {pct(b['precision'])} |"
        )
    e = s["entities"]
    lines += [
        "",
        "## Entity level (prompt cases)",
        "",
        "Each labelled value must be detected and must not appear raw in what is sent out.",
        "",
        f"* Entities: {e['tp'] + e['fn']} labelled, **{e['tp']} neutralized**, {e['fn']} missed, "
        f"{e['fp']} extra detections",
        f"* Entity recall **{pct(e['recall'])}**, entity precision **{pct(e['precision'])}**",
        "",
    ]

    def row(r: CaseResult) -> str:
        c = by_id[r.id]
        text = c.get("text") or json.dumps(c.get("arguments"))
        text = text.replace("\n", " ").replace("|", "\\|")
        if len(text) > 110:
            text = text[:107] + "..."
        detail = (
            r.detail.get("reason")
            or r.detail.get("leaked_entities")
            or r.detail.get("rules")
            or r.detail.get("signals")
        )
        note = c.get("notes", "")
        return f"| {r.id} | {r.category} | {text} | {detail} | {note} |"

    fns = [r for r in results if r.outcome == "FN"]
    fps = [r for r in results if r.outcome == "FP"]
    lines += ["## False negatives (protection gaps)", ""]
    if fns:
        lines += ["| Case | Category | Input | What happened | Notes |", "|---|---|---|---|---|"]
        lines += [row(r) for r in fns]
    else:
        lines.append("None.")
    lines += ["", "## False positives (utility cost)", ""]
    if fps:
        lines += ["| Case | Category | Input | What happened | Notes |", "|---|---|---|---|---|"]
        lines += [row(r) for r in fps]
    else:
        lines.append("None.")
    lines += [
        "",
        "## How to read this",
        "",
        "* Misses marked *expected miss* in the notes are known limitations kept in the corpus on purpose",
        "  (spelled-out digits, a card split across a sentence, social-engineering injections without",
        "  classic keywords). They are listed in `docs/tradeoffs-and-limitations.md` with what would fix them.",
        "* The regression gate (`make regression`) only requires that cases protected today stay protected.",
        "  Fixing a false negative grows the baseline; breaking a protected case fails the build.",
    ]
    REPORT_MD.parent.mkdir(exist_ok=True)
    REPORT_MD.write_text("\n".join(lines) + "\n")
    REPORT_JSON.write_text(
        json.dumps({"summary": s, "results": [r.__dict__ for r in results]}, indent=2) + "\n"
    )
    print(
        f"cases={o['cases']} recall={pct(o['recall'])} precision={pct(o['precision'])} "
        f"FN={o['fn']} FP={o['fp']} entity_recall={pct(e['recall'])}"
    )
    for r in fns:
        print("FN", r.id, r.detail)
    for r in fps:
        print("FP", r.id, r.detail)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
