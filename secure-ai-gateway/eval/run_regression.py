"""DLP regression gate for CI.

    python eval/run_regression.py            # exit 1 if any baseline-protected case regresses
    python eval/run_regression.py --update   # grow the baseline (refuses if anything regressed)

The baseline is the set of case ids the gateway protects today. A rule change, detector change,
classifier retrain, or policy edit must keep every one of them protected.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from aegis.classifier.model import load_default_classifier  # noqa: E402
from aegis.dlp.engine import DLPEngine  # noqa: E402
from aegis.guard.injection import InjectionDetector  # noqa: E402
from aegis.policy.regression import BASELINE, Evaluator, baseline_from, gate, load_baseline, load_cases  # noqa: E402
from aegis.policy.store import load_bundle_file  # noqa: E402

REPORT = ROOT / "reports" / "regression.md"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--update", action="store_true", help="grow the baseline with newly protected cases")
    ap.add_argument("--policy", default=None, help="policy bundle YAML to check (default: bundled policy)")
    ap.add_argument("--fail-on-utility", action="store_true", help="also fail on new false positives")
    args = ap.parse_args()

    bundle = load_bundle_file(args.policy)
    cases = load_cases()
    ev = Evaluator(DLPEngine.default("spacy"), load_default_classifier(), InjectionDetector())
    current = baseline_from(ev.evaluate(bundle.base, cases))
    baseline = load_baseline() if BASELINE.exists() else {"protected": [], "utility": []}
    report = gate(bundle, ev, baseline, cases)

    lines = [
        "# DLP regression gate",
        "",
        "Generated by `make regression`. Do not edit by hand.",
        "",
        f"* Baseline: {len(baseline['protected'])} protected cases, {len(baseline['utility'])} utility cases",
        f"* Scopes checked: {', '.join(report.scopes_checked)}",
        f"* Protection regressions: **{len(report.protection_regressions)}**",
        f"* Utility regressions (warnings): {len(report.utility_regressions)}",
        f"* Result: **{'PASS' if report.ok else 'FAIL'}**",
        "",
        "Protection regressions fail the build. Utility regressions are warnings: a legitimate prompt is now",
        "handled more strictly than before. They are expected in scopes with an intentionally stricter",
        "override, such as `acme/u-legal-bot`, which routes INTERNAL work to the local model.",
        "",
    ]
    for title, items in (
        ("Protection regressions", report.protection_regressions),
        ("Utility regressions", report.utility_regressions),
    ):
        if items:
            lines += [f"## {title}", "", "| Scope | Case | Category | Detail |", "|---|---|---|---|"]
            lines += [
                f"| {i['scope']} | {i['case']} | {i['category']} "
                f"| {i.get('reason') or i.get('rules') or i.get('route')} |"
                for i in items
            ]
            lines.append("")
    newly = sorted(set(current["protected"]) - set(baseline["protected"]))
    if newly:
        lines += ["## Newly protected (not yet in baseline)", "", ", ".join(newly), ""]
    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text("\n".join(lines) + "\n")

    print(
        f"baseline={len(baseline['protected'])} scopes={report.scopes_checked} "
        f"protection_regressions={len(report.protection_regressions)} "
        f"utility_regressions={len(report.utility_regressions)} newly_protected={len(newly)}"
    )
    for r in report.protection_regressions:
        print("REGRESSION", r)

    if args.update:
        if not report.ok:
            print("refusing to update the baseline while protection regressions exist", file=sys.stderr)
            return 1
        merged = {
            "protected": sorted(set(baseline["protected"]) | set(current["protected"])),
            "utility": sorted(set(current["utility"])),
        }
        BASELINE.parent.mkdir(parents=True, exist_ok=True)
        BASELINE.write_text(json.dumps(merged, indent=2) + "\n")
        print(f"baseline updated: {len(merged['protected'])} protected, {len(merged['utility'])} utility")
        return 0
    if not report.ok:
        return 1
    if args.fail_on_utility and report.utility_regressions:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
